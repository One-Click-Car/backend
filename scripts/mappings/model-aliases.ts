/**
 * מחפש שם דגם באנגלית לפי יצרן ושם עברי
 */
export function findEnglishModelName(make: string, hebrewModel: string): string | null {
  const makeModels = MODEL_ALIASES[make];
  if (!makeModels) return null;

  const normalized = hebrewModel.trim().toLowerCase();

  for (const [englishName, hebrewAliases] of Object.entries(makeModels)) {
    for (const alias of hebrewAliases) {
      if (alias.toLowerCase() === normalized) {
        return englishName;
      }
      if (normalized.includes(alias.toLowerCase()) || alias.toLowerCase().includes(normalized)) {
        return englishName;
      }
    }
  }

  return null;
}

/**
 * מחפש שם דגם באנגלית (גמיש - מנסה כמה אפשרויות)
 */
export function findEnglishModelNameFuzzy(make: string, model: string): string | null {
  // קודם בדיקה ישירה
  const direct = findEnglishModelName(make, model);
  if (direct) return direct;

  // אם השם כבר באנגלית - החזר אותו
  const makeModels = MODEL_ALIASES[make];
  if (makeModels && makeModels[model]) {
    return model;
  }

  // נסה לחלץ את השם ללא מספרים ותווים מיוחדים
  const cleanModel = model.replace(/[0-9\.,\-]/g, '').trim();
  if (cleanModel !== model) {
    const cleanResult = findEnglishModelName(make, cleanModel);
    if (cleanResult) return cleanResult;
  }

  return null;
}

/**
 * מחזיר את כל השמות האפשריים (עברית ואנגלית) לדגם
 */
export function getAllModelNames(make: string, model: string): string[] {
  const names: string[] = [model];
  const makeModels = MODEL_ALIASES[make];
  
  if (!makeModels) return names;

  // אם הוא באנגלית - הוסף את כל הכינויים העבריים
  if (makeModels[model]) {
    names.push(...makeModels[model]);
    return names;
  }

  // אם הוא בעברית - מצא את האנגלית והוסף את כולם
  const englishName = findEnglishModelName(make, model);
  if (englishName) {
    names.unshift(englishName);
    names.push(...(makeModels[englishName] || []));
  }

  return [...new Set(names)];
}

