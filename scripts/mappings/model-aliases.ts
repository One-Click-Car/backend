/**
 * מחזיר את כל הדגמים באנגלית של יצרן מסוים
 */
export function getEnglishModelsForMake(make: string): string[] {
  const makeModels = MODEL_ALIASES[make];
  if (!makeModels) return [];
  return Object.keys(makeModels);
}
